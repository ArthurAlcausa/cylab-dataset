-- Pacote financeiro (Oracle 19c): manutencao de faturas
CREATE TABLE faturas (
    fatura_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    valor_liquido   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_faturas_cli ON faturas (empresa_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

CREATE OR REPLACE PROCEDURE baixar_faturas(p_empresa IN NUMBER, p_usuario IN VARCHAR2) AS
    v_qtd NUMBER;
BEGIN
    log_execucao('baixar_faturas');
    EXECUTE IMMEDIATE 'UPDATE faturas SET status = ''BAIXADA'' WHERE empresa_id = :1' USING p_empresa;
    v_qtd := SQL%ROWCOUNT;
    INSERT INTO baixas_log (usuario, quantidade, data_baixa) VALUES (p_usuario, v_qtd, SYSDATE);
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END baixar_faturas;
/
