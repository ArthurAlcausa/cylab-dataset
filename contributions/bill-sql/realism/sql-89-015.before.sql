-- Pacote suporte (Oracle 19c): manutencao de chamados
CREATE TABLE chamados (
    chamado_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    sla_horas   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_chamados_cli ON chamados (conta_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

CREATE OR REPLACE PROCEDURE reabrir_chamados(p_conta IN VARCHAR2, p_motivo IN VARCHAR2) AS
BEGIN
    log_execucao('reabrir_chamados');
    EXECUTE IMMEDIATE 'UPDATE chamados SET status = ''REABERTO'' WHERE conta_id = ' || p_conta
        || ' AND status = ''FECHADO''';
    EXECUTE IMMEDIATE 'INSERT INTO chamados_hist (conta_id, motivo) VALUES (' || p_conta || ', ''' || p_motivo || ''')';
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END reabrir_chamados;
/
