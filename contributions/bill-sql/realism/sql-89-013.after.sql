-- Pacote compras (Oracle 19c): manutencao de contratos
CREATE TABLE contratos (
    contrato_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    valor_mensal   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_contratos_cli ON contratos (fornecedor_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

CREATE OR REPLACE PROCEDURE reindexar_particao(p_particao IN VARCHAR2) AS
    v_inicio TIMESTAMP := SYSTIMESTAMP;
    v_part   VARCHAR2(128);
BEGIN
    log_execucao('reindexar_particao');
    v_part := DBMS_ASSERT.SIMPLE_SQL_NAME(p_particao);
    EXECUTE IMMEDIATE 'ALTER INDEX ix_contratos_cli REBUILD PARTITION ' || DBMS_ASSERT.ENQUOTE_NAME(v_part) || ' ONLINE';
    DBMS_OUTPUT.PUT_LINE('duracao: ' || (SYSTIMESTAMP - v_inicio));
END reindexar_particao;
/
