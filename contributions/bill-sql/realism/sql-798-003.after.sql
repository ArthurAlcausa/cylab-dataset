-- Pacote logistica (Oracle 19c): manutencao de estoque_mov
CREATE TABLE estoque_mov (
    mov_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filial_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    quantidade   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_estoque_mov_cli ON estoque_mov (filial_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

CREATE USER logistica_int IDENTIFIED EXTERNALLY DEFAULT TABLESPACE users QUOTA 500M ON users;
CREATE USER logistica_ro IDENTIFIED GLOBALLY AS 'CN=logistica_ro,OU=dba,DC=corp';
GRANT CREATE SESSION TO logistica_int, logistica_ro;
GRANT SELECT, INSERT, UPDATE ON estoque_mov TO logistica_int;
GRANT SELECT ON estoque_mov TO logistica_ro;
