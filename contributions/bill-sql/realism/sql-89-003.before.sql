-- Pacote seguros (Oracle 19c): manutencao de apolices
CREATE TABLE apolices (
    apolice_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segurado_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    premio   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_apolices_cli ON apolices (segurado_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

CREATE OR REPLACE FUNCTION contar_apolices(p_status IN VARCHAR2) RETURN NUMBER AS
    v_total NUMBER;
    v_sql   VARCHAR2(4000);
BEGIN
    log_execucao('contar_apolices');
    v_sql := 'SELECT COUNT(*) FROM apolices WHERE status = ''' || p_status || '''';
    EXECUTE IMMEDIATE v_sql INTO v_total;
    RETURN v_total;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END contar_apolices;
/
