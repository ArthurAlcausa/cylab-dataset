-- Pacote vendas (Oracle 19c): manutencao de pedidos
CREATE TABLE pedidos (
    pedido_id   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(20)  DEFAULT 'ABERTO' NOT NULL,
    valor_total   NUMBER(14,2)  DEFAULT 0 NOT NULL,
    criado_em  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_pedidos_cli ON pedidos (cliente_id, criado_em);

CREATE OR REPLACE PROCEDURE log_execucao(p_rotina IN VARCHAR2) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO log_rotinas (rotina, usuario, executado_em)
    VALUES (p_rotina, USER, SYSTIMESTAMP);
    COMMIT;
END log_execucao;
/

/* Credencial do link fica no Oracle Wallet (mkstore), referenciada pelo alias CRMPRD */
CREATE DATABASE LINK lnk_crm
    CONNECT TO CURRENT_USER
    USING 'CRMPRD';

CREATE OR REPLACE VIEW vw_pedidos_crm AS
SELECT p.pedido_id, p.valor_total, c.segmento
  FROM pedidos p
  JOIN clientes@lnk_crm c ON c.cliente_id = p.cliente_id;

GRANT SELECT ON vw_pedidos_crm TO bi_leitura;
